type OTPConfig struct {
	CodeLength      int
	Expiry          time.Duration
	MaxAttempts     int
	RateLimitMax    int
	RateLimitWindow time.Duration
}

type otpEntry struct {
	code      string
	expiresAt time.Time
	attempts  int
	used      bool
}

type OTPService interface {
	Generate(ctx context.Context, identifier string) (string, error)
	Validate(ctx context.Context, identifier, code string) (bool, error)
}

type otpService struct {
	config   OTPConfig
	delivery EmailDelivery
	mu       sync.Mutex
	entries  map[string]*otpEntry
	// rate limiting: identifier -> list of generation timestamps
	rateLog map[string][]time.Time
}

func NewOTPService(config OTPConfig) OTPService {
	return &otpService{
		config:  config,
		entries: make(map[string]*otpEntry),
		rateLog: make(map[string][]time.Time),
	}
}

func NewOTPServiceWithDelivery(config OTPConfig, delivery EmailDelivery) OTPService {
	return &otpService{
		config:   config,
		delivery: delivery,
		entries:  make(map[string]*otpEntry),
		rateLog:  make(map[string][]time.Time),
	}
}

func generateCode(length int) (string, error) {
	code := ""
	for i := 0; i < length; i++ {
		n, err := rand.Int(rand.Reader, big.NewInt(10))
		if err != nil {
			return "", err
		}
		code += fmt.Sprintf("%d", n.Int64())
	}
	return code, nil
}

func (s *otpService) Generate(ctx context.Context, identifier string) (string, error) {
	// F-032 (audit 2026-05-30): only the in-memory entries/rateLog maps are
	// shared mutable state, so the mutex is held for that read/write window
	// alone. SendOTP is an SMTP round-trip and must run lock-free, otherwise a
	// single slow/timing-out send serializes every concurrent registration OTP
	// behind one global lock (effective DoS on sign-up). On send failure we
	// re-acquire and roll back both the stored entry and the rate-log slot so a
	// failed send leaves no usable code and does not consume the caller's quota.
	s.mu.Lock()

	// Rate limiting
	now := time.Now()
	windowStart := now.Add(-s.config.RateLimitWindow)
	var recent []time.Time
	for _, t := range s.rateLog[identifier] {
		if t.After(windowStart) {
			recent = append(recent, t)
		}
	}
	if len(recent) >= s.config.RateLimitMax {
		s.mu.Unlock()
		return "", errors.New("rate limit exceeded")
	}

	code, err := generateCode(s.config.CodeLength)
	if err != nil {
		s.mu.Unlock()
		return "", err
	}

	s.entries[identifier] = &otpEntry{
		code:      code,
		expiresAt: now.Add(s.config.Expiry),
		attempts:  0,
		used:      false,
	}
	s.rateLog[identifier] = append(recent, now)
	s.mu.Unlock()

	if s.delivery != nil {
		if err := s.delivery.SendOTP(ctx, identifier, code); err != nil {
			// Roll back the entry and the rate-log slot we just recorded so the
			// failed send is not chargeable and the unsent code is unusable.
			s.mu.Lock()
			delete(s.entries, identifier)
			s.rateLog[identifier] = recent
			s.mu.Unlock()
			return "", err
		}
	}

	return code, nil
}

func (s *otpService) Validate(ctx context.Context, identifier, code string) (bool, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	entry, ok := s.entries[identifier]
	if !ok {
		return false, nil
	}

	if entry.attempts >= s.config.MaxAttempts {
		return false, errors.New("max attempts exceeded")
	}

	if entry.used {
		return false, nil
	}

	if time.Now().After(entry.expiresAt) {
		return false, nil
	}

	entry.attempts++

	if subtle.ConstantTimeCompare([]byte(entry.code), []byte(code)) != 1 {
		if entry.attempts >= s.config.MaxAttempts {
			// Already counted, next call will error
		}
		return false, nil
	}

	entry.used = true
	return true, nil
}

// ──────────────────────────── JWT Service ────────────────────────────

type JWTConfig struct {
	AccessTokenExpiry  time.Duration
	RefreshTokenExpiry time.Duration
	MaxSessions        int
}

type TokenClaims struct {
	Sub          string
	WorkspaceID  string
	Role         string // Workspace role: Owner/Admin/Editor/Viewer
	PlatformRole string // Platform role: super_admin/admin/dealer/photographer/team_member/client
	StateID      string
	// F-007 (M17 hardening wave 1): MFAVerified is true iff this access token
	// was issued after a successful TOTP verification in the login flow.
	// Middleware gates TOTP-mandatory roles (platform_admin, platform_staff,
	// workspace_owner, workspace_admin, workspace_member) on MFAVerified==true
	// OR an active grace window (users.mfa_grace_until).
	// Zero value (false) is the safe default for legacy tokens without the claim.
	MFAVerified bool
	// S5-G1 (audit HIGH): Impersonation is true iff this access token was minted
	// by an admin impersonating a tenant (AdminUserService.ImpersonateUser).
	// Middleware (RejectImpersonationWrites) gates mutating HTTP methods on this
	// flag so impersonated sessions are truly read-only. Zero value (false) is the
	// safe default for every normal login/refresh token — it is set in exactly one
	// place (ImpersonateUser) and omitted/false everywhere else.
	Impersonation bool
	ExpiresAt     time.Time
}

type RefreshTokenInfo struct {
	Sub       string
	FamilyID  string
	ExpiresAt time.Time
}

type JWTService interface {
	GenerateAccessToken(ctx context.Context, claims TokenClaims) (string, error)
	ParseAccessToken(ctx context.Context, tokenStr string) (*TokenClaims, error)
	GenerateRefreshToken(ctx context.Context, userID, familyID string) (string, error)
	GenerateRefreshTokenWithClaims(ctx context.Context, userID, familyID, workspaceID, role, platformRole, stateID string) (string, error)
	// F-007 (M17 wave 2): variant that persists the mfa_verified state
	// of the minting login. RotateRefreshToken carries this forward so
	// refreshed access tokens keep their MFA state.
	GenerateRefreshTokenWithMFA(ctx context.Context, userID, familyID, workspaceID, role, platformRole, stateID string, mfaVerified bool) (string, error)
	RotateRefreshToken(ctx context.Context, oldToken string) (newAccess string, newRefresh string, err error)
	InspectRefreshToken(ctx context.Context, tokenStr string) (*RefreshTokenInfo, error)
	RevokeSession(ctx context.Context, familyID string) error
}

