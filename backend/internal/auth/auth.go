func NewJWTService(config JWTConfig) JWTService {
	key, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		log.Fatalf("auth: failed to generate RSA key for JWT service: %v", err)
	}
	return &jwtService{
		config:       config,
		privateKey:   key,
		publicKey:    &key.PublicKey,
		refreshStore: NewInMemoryRefreshStore(),
	}
}

// WithRefreshStore replaces the default in-memory refresh session store
// with a caller-provided implementation. main.go uses this during
// bootstrap to wire the DB-backed RefreshSessionRepo so refresh sessions
// survive service restarts (F-006 Part B). Returns the same service
// pointer for call chaining. Passing nil is a no-op — the existing
// in-memory store is retained.
func (s *jwtService) WithRefreshStore(store RefreshSessionStore) JWTService {
	if store == nil {
		return s
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.refreshStore = store
	return s
}

func (s *jwtService) GenerateAccessToken(ctx context.Context, claims TokenClaims) (string, error) {
	if claims.Sub == "" || claims.WorkspaceID == "" || claims.Role == "" || claims.StateID == "" {
		return "", errors.New("missing required claims")
	}
	if claims.PlatformRole == "" {
		claims.PlatformRole = "photographer"
	}

	now := time.Now()
	token := jwt.NewWithClaims(jwt.SigningMethodRS256, jwt.MapClaims{
		"sub":           claims.Sub,
		"workspace_id":  claims.WorkspaceID,
		"role":          claims.Role,
		"platform_role": claims.PlatformRole,
		"state_id":      claims.StateID,
		"mfa_verified":  claims.MFAVerified,            // F-007 (M17 wave 1): second-factor state for mandatory-MFA roles
		"impersonation": claims.Impersonation,          // S5-G1: read-only admin-impersonation marker (false for normal tokens)
		"iss":           jwtIssuer,                     // F-103: bind issuer
		"aud":           jwt.ClaimStrings{jwtAudience}, // F-103: bind audience
		"exp":           now.Add(s.config.AccessTokenExpiry).Unix(),
		"iat":           now.Unix(),
	})

	return token.SignedString(s.privateKey)
}

func (s *jwtService) ParseAccessToken(ctx context.Context, tokenStr string) (*TokenClaims, error) {
	token, err := jwt.Parse(tokenStr, func(token *jwt.Token) (interface{}, error) {
		if _, ok := token.Method.(*jwt.SigningMethodRSA); !ok {
			return nil, fmt.Errorf("unexpected signing method: %v", token.Header["alg"])
		}
		return s.publicKey, nil
	},
		// F-103: reject tokens not issued for this service (token confusion /
		// cross-service replay) by enforcing the issuer + audience binding.
		jwt.WithIssuer(jwtIssuer),
		jwt.WithAudience(jwtAudience),
	)
	if err != nil {
		return nil, err
	}

	mapClaims, ok := token.Claims.(jwt.MapClaims)
	if !ok || !token.Valid {
		return nil, errors.New("invalid token")
	}

	exp, _ := mapClaims.GetExpirationTime()
	var expiresAt time.Time
	if exp != nil {
		expiresAt = exp.Time
	}

	platformRole, _ := mapClaims["platform_role"].(string)
	if platformRole == "" {
		platformRole = "photographer"
	}

	// F-007 (M17 wave 1): mfa_verified is optional — legacy tokens without the
	// claim parse as false. The type assertion pattern is the same as the other
	// optional fields above.
	mfaVerified, _ := mapClaims["mfa_verified"].(bool)

	// S5-G1: impersonation is optional — legacy/normal tokens without the claim
	// parse as false (read-write). Only admin-minted impersonation tokens set it.
	impersonation, _ := mapClaims["impersonation"].(bool)

	return &TokenClaims{
		Sub:           mapClaims["sub"].(string),
		WorkspaceID:   mapClaims["workspace_id"].(string),
		Role:          mapClaims["role"].(string),
		PlatformRole:  platformRole,
		StateID:       mapClaims["state_id"].(string),
		MFAVerified:   mfaVerified,
		Impersonation: impersonation,
		ExpiresAt:     expiresAt,
	}, nil
}

func (s *jwtService) generateRefreshTokenString() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return fmt.Sprintf("%x", b), nil
}

// enforceSessionLimit checks whether creating a new session for the
// given (user, family) pair would exceed MaxSessions. A rotate within
// an existing family does not count as a new session. Returns an error
// if the limit would be exceeded.
func (s *jwtService) enforceSessionLimit(ctx context.Context, userID, familyID string) error {
	hasFamily, err := s.refreshStore.UserHasFamily(ctx, userID, familyID)
	if err != nil {
		return fmt.Errorf("refresh store: check existing family: %w", err)
	}
	if hasFamily {
		return nil // rotating within an existing family is always allowed
	}
	active, err := s.refreshStore.CountActiveFamiliesForUser(ctx, userID)
	if err != nil {
		return fmt.Errorf("refresh store: count active families: %w", err)
	}
	if active >= s.config.MaxSessions {
		return errors.New("max concurrent sessions exceeded")
	}
	return nil
}

func (s *jwtService) GenerateRefreshToken(ctx context.Context, userID, familyID string) (string, error) {
	if err := s.enforceSessionLimit(ctx, userID, familyID); err != nil {
		return "", err
	}

	tokenStr, err := s.generateRefreshTokenString()
	if err != nil {
		return "", err
	}

	if err := s.refreshStore.Create(ctx, RefreshSessionEntry{
		RawToken:  tokenStr,
		Sub:       userID,
		FamilyID:  familyID,
		ExpiresAt: time.Now().Add(s.config.RefreshTokenExpiry),
	}); err != nil {
		return "", fmt.Errorf("refresh store: create: %w", err)
	}
	return tokenStr, nil
}

func (s *jwtService) GenerateRefreshTokenWithClaims(ctx context.Context, userID, familyID, workspaceID, role, platformRole, stateID string) (string, error) {
	// Backward-compatible wrapper: legacy callers that don't know about
	// MFA state get mfa_verified=false, matching their pre-M17 semantics.
	return s.GenerateRefreshTokenWithMFA(ctx, userID, familyID, workspaceID, role, platformRole, stateID, false)
}

// GenerateRefreshTokenWithMFA is the F-007 variant that persists the
// mfa_verified state of the minting login. The VerifyTOTP handler calls
// this with mfaVerified=true after a successful second-factor check so
// that subsequent access-token refreshes preserve the MFA claim.
func (s *jwtService) GenerateRefreshTokenWithMFA(ctx context.Context, userID, familyID, workspaceID, role, platformRole, stateID string, mfaVerified bool) (string, error) {
	if err := s.enforceSessionLimit(ctx, userID, familyID); err != nil {
		return "", err
	}

	tokenStr, err := s.generateRefreshTokenString()
	if err != nil {
		return "", err
	}

	if err := s.refreshStore.Create(ctx, RefreshSessionEntry{
		RawToken:     tokenStr,
		Sub:          userID,
		FamilyID:     familyID,
		WorkspaceID:  workspaceID,
		Role:         role,
		PlatformRole: platformRole,
		StateID:      stateID,
		MFAVerified:  mfaVerified,
		ExpiresAt:    time.Now().Add(s.config.RefreshTokenExpiry),
	}); err != nil {
		return "", fmt.Errorf("refresh store: create: %w", err)
	}
	return tokenStr, nil
}

func (s *jwtService) RotateRefreshToken(ctx context.Context, oldToken string) (string, string, error) {
	entry, err := s.refreshStore.Get(ctx, oldToken)
	if err != nil {
		if errors.Is(err, ErrRefreshNotFound) {
			return "", "", errors.New("refresh token not found")
		}
		return "", "", fmt.Errorf("refresh store: get: %w", err)
	}

	// Check family revocation first — if the family is dead, nothing
	// under it can be rotated, even if the individual row looks clean.
	familyRevoked, err := s.refreshStore.IsFamilyRevoked(ctx, entry.FamilyID)
	if err != nil {
		return "", "", fmt.Errorf("refresh store: check family revocation: %w", err)
	}
	if entry.Revoked || familyRevoked {
		// Token reuse detected (or the whole family is already dead).
		// Kill the family again for idempotency.
		_ = s.refreshStore.RevokeFamily(ctx, entry.FamilyID)
		return "", "", errors.New("refresh token reuse detected, family revoked")
	}

	if entry.Used {
		// Seeing a second Rotate for the same token means an attacker
		// has the refresh secret. Nuke the family.
		_ = s.refreshStore.RevokeFamily(ctx, entry.FamilyID)
		return "", "", errors.New("refresh token reuse detected, family revoked")
	}

	if time.Now().After(entry.ExpiresAt) {
		return "", "", errors.New("refresh token expired")
	}

	// Mark the old token used BEFORE issuing the new one so a racing
	// rotate hits the reuse-detection path.
	if err := s.refreshStore.MarkUsed(ctx, oldToken); err != nil {
		return "", "", fmt.Errorf("refresh store: mark used: %w", err)
	}

	// Generate the new refresh token (sliding window) and persist it.
	newTokenStr, err := s.generateRefreshTokenString()
	if err != nil {
		return "", "", err
	}
	if err := s.refreshStore.Create(ctx, RefreshSessionEntry{
		RawToken:     newTokenStr,
		Sub:          entry.Sub,
		FamilyID:     entry.FamilyID,
		WorkspaceID:  entry.WorkspaceID,
		Role:         entry.Role,
		PlatformRole: entry.PlatformRole,
		StateID:      entry.StateID,
		MFAVerified:  entry.MFAVerified, // F-007 wave 2: preserve MFA state through rotation
		ExpiresAt:    time.Now().Add(s.config.RefreshTokenExpiry),
	}); err != nil {
		return "", "", fmt.Errorf("refresh store: create rotated: %w", err)
	}

	// Generate the new access token — carry forward claims from the
	// original login. Defaults preserve the pre-F-006-Part-B behavior.
	wsID := entry.WorkspaceID
	role := entry.Role
	pRole := entry.PlatformRole
	stID := entry.StateID
	if wsID == "" {
		wsID = "pending-onboarding"
	}
	if role == "" {
		role = "Owner"
	}
	if pRole == "" {
		pRole = "photographer"
	}
	if stID == "" {
		stID = "pending-onboarding"
	}

	s.mu.Lock()
	accessToken, err := s.generateAccessTokenUnlocked(TokenClaims{
		Sub:          entry.Sub,
		WorkspaceID:  wsID,
		Role:         role,
		PlatformRole: pRole,
		StateID:      stID,
		MFAVerified:  entry.MFAVerified, // F-007 wave 2: carry forward MFA state to rotated access token
	})
	s.mu.Unlock()
	if err != nil {
		return "", "", err
	}

	return accessToken, newTokenStr, nil
}

func (s *jwtService) generateAccessTokenUnlocked(claims TokenClaims) (string, error) {
	if claims.PlatformRole == "" {
		claims.PlatformRole = "photographer"
	}
	now := time.Now()
	token := jwt.NewWithClaims(jwt.SigningMethodRS256, jwt.MapClaims{
		"sub":           claims.Sub,
		"workspace_id":  claims.WorkspaceID,
		"role":          claims.Role,
		"platform_role": claims.PlatformRole,
		"state_id":      claims.StateID,
		"mfa_verified":  claims.MFAVerified,            // F-007 (M17 wave 1): carried from caller (RotateRefreshToken sets false until wave 2 adds session-level persistence)
		"impersonation": claims.Impersonation,          // S5-G1: carried from caller; refresh rotation never sets it true (impersonation tokens are non-refreshable access tokens)
		"iss":           jwtIssuer,                     // F-103: bind issuer
		"aud":           jwt.ClaimStrings{jwtAudience}, // F-103: bind audience
		"exp":           now.Add(s.config.AccessTokenExpiry).Unix(),
		"iat":           now.Unix(),
	})
	return token.SignedString(s.privateKey)
}

func (s *jwtService) InspectRefreshToken(ctx context.Context, tokenStr string) (*RefreshTokenInfo, error) {
	entry, err := s.refreshStore.Get(ctx, tokenStr)
	if err != nil {
		if errors.Is(err, ErrRefreshNotFound) {
			return nil, errors.New("refresh token not found")
		}
		return nil, fmt.Errorf("refresh store: get: %w", err)
	}
	return &RefreshTokenInfo{
		Sub:       entry.Sub,
		FamilyID:  entry.FamilyID,
		ExpiresAt: entry.ExpiresAt,
	}, nil
}

func (s *jwtService) RevokeSession(ctx context.Context, familyID string) error {
	if err := s.refreshStore.RevokeFamily(ctx, familyID); err != nil {
		return fmt.Errorf("refresh store: revoke family: %w", err)
	}
	return nil
}

