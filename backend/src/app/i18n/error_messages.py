def get_error_message(
    key: str | ErrorMessageKey,
    locale: str = "en",
    fallback_locale: str = "en",
) -> str:
    """Get a localized error message.

    Args:
        key: Error message key (string or ErrorMessageKey enum)
        locale: Target language code (e.g., 'hi', 'te')
        fallback_locale: Fallback language if translation is missing

    Returns:
        Localized error message, falling back to English if not found
    """
    # Convert enum to string if needed
    if isinstance(key, ErrorMessageKey):
        key = key.value

    # Normalize locale to base language code
    base_locale = locale.split("-")[0].lower()

    # Get message translations for this key
    translations = ERROR_MESSAGES.get(key, {})

    # Try requested locale, then fallback, then English
    if base_locale in translations:
        return translations[base_locale]
    if fallback_locale in translations:
        return translations[fallback_locale]
    if "en" in translations:
        return translations["en"]

    # If no translation found, return the key itself
    return key


def get_error_messages_for_locale(locale: str = "en") -> dict[str, str]:
    """Get all error messages for a specific locale.

    Useful for bulk loading translations on the client side.

    Args:
        locale: Target language code

    Returns:
        Dictionary mapping error keys to localized messages
    """
    base_locale = locale.split("-")[0].lower()

    result: dict[str, str] = {}
    for key, translations in ERROR_MESSAGES.items():
        # Get string key
        key_str = key.value if isinstance(key, ErrorMessageKey) else key

        # Get translation with fallback to English
        if base_locale in translations:
            result[key_str] = translations[base_locale]
        elif "en" in translations:
            result[key_str] = translations["en"]
        else:
            result[key_str] = key_str

    return result


def is_locale_supported(locale: str) -> bool:
    """Check if a locale is supported for error messages.

    Args:
        locale: Language code to check

    Returns:
        True if locale is supported
    """
    base_locale = locale.split("-")[0].lower()
    supported = {"en", "hi", "te", "ta", "kn", "ml", "as", "bn", "gu", "mr", "or", "pa", "ur"}
    return base_locale in supported
